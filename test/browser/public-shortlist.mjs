/** Chromium acceptance of local public assets with intercepted synthetic traffic only.
 * Set ATRIUM_PLAYWRIGHT_MODULE, ATRIUM_CHROME_EXECUTABLE, ATRIUM_BROWSER_ARTIFACTS.
 */
import assert from 'node:assert/strict'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(process.env.ATRIUM_PLAYWRIGHT_MODULE ? pathToFileURL(process.env.ATRIUM_PLAYWRIGHT_MODULE).href : 'playwright')
const publicDir = new URL('../../public/', import.meta.url)
const dir = resolve(process.env.ATRIUM_BROWSER_ARTIFACTS || '/tmp/atrium-public-shortlist-browser')
await mkdir(dir, { recursive: true })
const checks = [], errors = [], screenshots = []
const browser = await chromium.launch({ headless: true, ...(process.env.ATRIUM_CHROME_EXECUTABLE ? { executablePath: process.env.ATRIUM_CHROME_EXECUTABLE } : {}) })
try {
  for (const width of [320, 390, 1280]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce', colorScheme: 'light' })
    await context.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.origin !== 'https://larkin.example') return route.abort()
      const name = url.pathname === '/' ? 'index.html' : url.pathname.slice(1)
      if (!['index.html','app.js','shortlist.js','styles.css','floorplans.html','amenities.html'].includes(name)) return route.abort()
      await route.fulfill({ body: await readFile(new URL(name, publicDir)), contentType: name.endsWith('.js') ? 'application/javascript' : name.endsWith('.css') ? 'text/css' : 'text/html' })
    })
    await context.addInitScript(() => {
      Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => { if (window.rejectCopy) throw Error('denied'); window.copiedLink = text } } })
    })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    const check = (name) => checks.push({ width, name })
    await page.goto('https://larkin.example/#availability')
    const rows = page.locator('#avail-body tr')
    const allCount = await rows.count()
    assert.ok(allCount > 5)
    const save = id => page.locator(`[data-shortlist-unit="${id}"]`)
    await save('19A').scrollIntoViewIfNeeded()
    const beforeY = await page.evaluate(() => scrollY)
    const beforeTop = (await save('19A').boundingBox()).y
    await save('19A').click()
    console.log(JSON.stringify({ width, beforeY, afterY: await page.evaluate(() => scrollY), beforeTop, afterTop: (await save('19A').boundingBox()).y }))
    assert.ok(Math.abs((await save('19A').boundingBox()).y - beforeTop) < 3, 'selection stays at the same visible position')
    assert.equal(await save('19A').getAttribute('aria-pressed'), 'true')
    assert.equal(await page.evaluate(() => document.activeElement.dataset.shortlistUnit), '19A')
    assert.equal(await rows.count(), allCount)
    check('select retains table and focus')
    const ids = await page.locator('[data-shortlist-unit]').evaluateAll(nodes => nodes.map(n => n.dataset.shortlistUnit).filter(id => id !== '19A').slice(0, 5))
    for (const id of ids.slice(0, 4)) await save(id).click()
    await save(ids[4]).click()
    assert.equal(await page.locator('#shortlist-count').textContent(), '5 of 5 selected')
    assert.match(await page.locator('#shortlist-status').textContent(), /full/)
    check('sixth selection refused without losing existing choices')
    await page.locator('#shortlist-copy').click()
    const link = await page.locator('#shortlist-link').inputValue()
    assert.equal(await page.evaluate(() => window.copiedLink), link)
    await page.goto(link)
    assert.equal(await rows.count(), 5)
    check('copied link reopens exact five units')
    await page.locator('#sort').selectOption('rent-desc')
    assert.equal(await rows.count(), 5)
    await page.locator('#bed-filters [data-beds="3"]').click()
    assert.ok(await rows.count() >= 1)
    assert.ok(await rows.count() <= 5)
    assert.ok((await page.locator('#avail-body').textContent()).includes('19A'))
    check('sort and bedroom filters operate within shortlist')
    await page.locator('#shortlist-view').click()
    assert.equal(await rows.count(), allCount)
    await page.locator('#shortlist-view').click()
    await page.locator('[data-remove-unit="19A"]').click()
    assert.equal(await rows.count(), 4)
    check('browse all and remove update actual selection')
    await page.evaluate(() => { window.rejectCopy = true })
    await page.locator('#shortlist-copy').click()
    assert.match(await page.locator('#shortlist-status').textContent(), /manually/)
    assert.equal(await page.evaluate(() => document.activeElement.id), 'shortlist-link')
    check('clipboard refusal exposes selected manual-copy link')
    await page.locator('#shortlist-clear').click()
    assert.equal(await rows.count(), allCount)
    assert.equal(await page.locator('#shortlist-share').isVisible(), false)
    await page.reload()
    assert.equal(await rows.count(), allCount)
    check('clear removes original URL selection and survives reload')
    await page.goto('https://larkin.example/#availability?units=19A,99ZZ')
    assert.equal(await rows.count(), 1)
    assert.match(await page.locator('#shortlist-notice').textContent(), /1 selected residence is no longer/)
    check('partially missing shortlist explains coverage')
    await page.goto('https://larkin.example/#availability?units=99ZZ')
    assert.equal(await rows.count(), 0)
    assert.equal(await page.locator('#shortlist-view').isEnabled(), true)
    check('fully missing link never silently shows unrelated units')
    await page.goto('https://larkin.example/#availability?units=%3Cscript%3E')
    assert.equal(await rows.count(), 0)
    assert.match(await page.locator('#shortlist-notice').textContent(), /invalid/)
    await page.locator('#shortlist-view').click()
    assert.equal(await rows.count(), allCount)
    check('invalid link has explicit safe recovery')
    const pendingId = await page.locator('#avail-body tr').filter({ has: page.locator('.u-tag--pending') }).first().locator('[data-shortlist-unit]').getAttribute('data-shortlist-unit')
    assert.ok(pendingId)
    await page.goto('https://larkin.example/#availability?units=19A,' + pendingId)
    assert.match(await page.locator('#shortlist-items').textContent(), /Under application/)
    assert.equal(await page.locator('#avail-body .u-tag--pending').count(), 1)
    check('pending unit stays visibly under application')
    await page.evaluate(() => { location.hash = '#availability' })
    await page.waitForFunction(() => document.querySelector('#shortlist-view').getAttribute('aria-pressed') === 'false')
    assert.equal(await rows.count(), allCount)
    await page.evaluate(() => { location.hash = '#availability?units=19A' })
    await page.waitForFunction(() => document.querySelectorAll('#avail-body tr').length === 1)
    check('same-document link navigation applies and clears filtering')
    await page.locator('#shortlist-view').focus()
    await page.keyboard.press('Enter')
    assert.equal(await rows.count(), allCount)
    check('keyboard operates shortlist control')
    await page.locator('#shortlist-view').click()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no page overflow')
    await page.locator('.shortlist').scrollIntoViewIfNeeded()
    const shot = resolve(dir, `shortlist-${width}.png`)
    await page.screenshot({ path: shot }); screenshots.push(shot)
    check('responsive layout and screenshot')
    await page.goto('https://larkin.example/floorplans.html')
    await page.goto('https://larkin.example/amenities.html')
    check('other public pages load without shortlist dependency errors')
    await context.close()
  }
  assert.deepEqual(errors, [])
} finally { await browser.close() }
await writeFile(resolve(dir, 'results.json'), JSON.stringify({ at: new Date().toISOString(), checks, errors, screenshots }, null, 2))
console.log(JSON.stringify({ passed: checks.length, errors, screenshots }))
